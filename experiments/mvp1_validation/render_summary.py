#!/usr/bin/env python3
"""Renders experiments/mvp1_validation/results/*.json into the human-
readable Markdown evidence summary committed alongside them."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", required=True, type=Path)
    ap.add_argument("--matrix", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    corpus = json.loads(args.corpus.read_text())
    matrix = json.loads(args.matrix.read_text())

    lines = []
    lines.append("# HORO-1127 MVP 1.0 release-gate evidence summary\n")
    lines.append(
        "Generated by `experiments/mvp1_validation/run_corpus.py` and "
        "`run_validation_matrix.py`, driving the real compiled `libra-governor` "
        "binary as a subprocess (real JSON on stdin, real Unix-socket daemon, "
        "real SQLite ledger) — no Rust function called in-process.\n"
    )

    s = corpus["summary"]
    lines.append("## Corpus\n")
    lines.append(f"- Corpus size: **{corpus['corpus_size']}**")
    lines.append(f"- Preflight success rate: **{s['preflight_success_rate']:.1%}**")
    lines.append(f"- Estimate-present rate: **{s['estimate_present_rate']:.1%}**")
    lines.append(f"- Receipt-reconstruction success rate: **{s['receipt_reconstruction_rate']:.1%}**")
    lines.append(f"- Stop hook safe-outcome rate: **{s['stop_ok_rate']:.1%}**")
    lines.append(f"- Tasks with any error: **{s['tasks_with_errors']}**\n")

    outcomes = {}
    fixtures = {}
    for t in corpus["tasks"]:
        outcomes[t["outcome"]] = outcomes.get(t["outcome"], 0) + 1
        fixtures[t["fixture"]] = fixtures.get(t["fixture"], 0) + 1
    lines.append(f"- Outcome distribution across all finalized receipts: `{outcomes}`")
    lines.append(f"- Fixture distribution: `{fixtures}`\n")

    lines.append("## Required validation matrix\n")
    lines.append("| Check | Result |")
    lines.append("|---|---|")
    for name, r in matrix.items():
        status = "PASS" if r["passed"] else "FAIL"
        lines.append(f"| `{name}` | **{status}** |")
    lines.append("")

    lines.append("### Detail\n")
    for name, r in matrix.items():
        status = "PASS" if r["passed"] else "FAIL"
        lines.append(f"**{name}** — {status}\n")
        lines.append(f"> {r['detail']}\n")

    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
